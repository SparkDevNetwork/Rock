using System;
using System.Collections.Generic;

namespace Rock.Data;

/// <summary>
/// The shape of a database as read from its <c>sys.*</c> catalog views.
/// Used by the schema checks to compare a database with what the entity
/// model expects or with another database.
/// </summary>
internal sealed class SchemaCatalog
{
    /// <summary>
    /// The user tables, keyed by <c>schema.table</c>.
    /// </summary>
    public Dictionary<string, SchemaCatalogTable> Tables { get; } = new Dictionary<string, SchemaCatalogTable>( StringComparer.OrdinalIgnoreCase );

    /// <summary>
    /// The views and their columns, keyed by <c>schema.view</c>. Only the
    /// mapping check uses them, since EF maps some entities to views.
    /// Equivalence compares view definitions through <see cref="Modules"/>.
    /// </summary>
    public Dictionary<string, SchemaCatalogTable> Views { get; } = new Dictionary<string, SchemaCatalogTable>( StringComparer.OrdinalIgnoreCase );

    /// <summary>
    /// The views, procedures, functions and triggers, keyed by <c>schema.name</c>.
    /// </summary>
    public Dictionary<string, SchemaCatalogModule> Modules { get; } = new Dictionary<string, SchemaCatalogModule>( StringComparer.OrdinalIgnoreCase );

    /// <summary>
    /// Adds a table to the catalog.
    /// </summary>
    /// <param name="table">The table to add.</param>
    /// <returns>The table that was added.</returns>
    public SchemaCatalogTable AddTable( SchemaCatalogTable table )
    {
        Tables.Add( table.Key, table );

        return table;
    }
}

/// <summary>
/// A user table in a <see cref="SchemaCatalog"/>.
/// </summary>
internal sealed class SchemaCatalogTable
{
    /// <summary>
    /// The schema the table belongs to, such as <c>dbo</c>.
    /// </summary>
    public string Schema { get; set; } = "dbo";

    /// <summary>
    /// The table name.
    /// </summary>
    public string Name { get; set; }

    /// <summary>
    /// The <c>schema.table</c> key used in catalogs and findings.
    /// </summary>
    public string Key => $"{Schema}.{Name}";

    /// <summary>
    /// The columns, keyed by name.
    /// </summary>
    public Dictionary<string, SchemaCatalogColumn> Columns { get; } = new Dictionary<string, SchemaCatalogColumn>( StringComparer.OrdinalIgnoreCase );

    /// <summary>
    /// The primary key, or <c>null</c> when the table has none.
    /// </summary>
    public SchemaCatalogIndex PrimaryKey { get; set; }

    /// <summary>
    /// The indexes and unique constraints other than the primary key.
    /// </summary>
    public List<SchemaCatalogIndex> Indexes { get; } = new List<SchemaCatalogIndex>();

    /// <summary>
    /// The foreign keys declared on this table.
    /// </summary>
    public List<SchemaCatalogForeignKey> ForeignKeys { get; } = new List<SchemaCatalogForeignKey>();

    /// <summary>
    /// The definitions of the check constraints on this table. Check
    /// constraint names are often generated by SQL Server, so only the
    /// definitions are compared.
    /// </summary>
    public List<string> CheckConstraints { get; } = new List<string>();

    /// <summary>
    /// Adds a column to the table.
    /// </summary>
    /// <param name="column">The column to add.</param>
    /// <returns>This table, so calls can be chained.</returns>
    public SchemaCatalogTable AddColumn( SchemaCatalogColumn column )
    {
        Columns.Add( column.Name, column );

        return this;
    }
}

/// <summary>
/// A column of a <see cref="SchemaCatalogTable"/>.
/// </summary>
internal sealed class SchemaCatalogColumn
{
    /// <summary>
    /// The column name.
    /// </summary>
    public string Name { get; set; }

    /// <summary>
    /// The store type name in lower case, such as <c>nvarchar</c> or
    /// <c>decimal</c>. <c>rowversion</c> is reported as <c>timestamp</c>.
    /// </summary>
    public string StoreType { get; set; }

    /// <summary>
    /// The length in characters (or bytes for binary types), <c>-1</c>
    /// for <c>max</c>, or <c>null</c> when the type has no length.
    /// </summary>
    public int? MaxLength { get; set; }

    /// <summary>
    /// The precision for <c>decimal</c> and <c>numeric</c>, or the
    /// fractional seconds precision for <c>datetime2</c>, <c>time</c> and
    /// <c>datetimeoffset</c>. <c>null</c> for other types.
    /// </summary>
    public int? Precision { get; set; }

    /// <summary>
    /// The scale for <c>decimal</c> and <c>numeric</c>, otherwise <c>null</c>.
    /// </summary>
    public int? Scale { get; set; }

    /// <summary>
    /// Whether the column allows <c>NULL</c>.
    /// </summary>
    public bool IsNullable { get; set; }

    /// <summary>
    /// Whether the column is an identity column.
    /// </summary>
    public bool IsIdentity { get; set; }

    /// <summary>
    /// The computed column definition, or <c>null</c> when the column is not computed.
    /// </summary>
    public string ComputedDefinition { get; set; }

    /// <summary>
    /// The default constraint definition, or <c>null</c> when the column has no default.
    /// </summary>
    public string DefaultDefinition { get; set; }

    /// <summary>
    /// Whether SQL Server supplies a value when an insert omits this
    /// column: it is nullable, has a default, is an identity, is computed
    /// or is a <c>timestamp</c>.
    /// </summary>
    public bool IsValueOptionalOnInsert => IsNullable
        || DefaultDefinition != null
        || IsIdentity
        || ComputedDefinition != null
        || StoreType == "timestamp";
}

/// <summary>
/// An index, unique constraint or primary key.
/// </summary>
internal sealed class SchemaCatalogIndex
{
    /// <summary>
    /// The index or constraint name.
    /// </summary>
    public string Name { get; set; }

    /// <summary>
    /// Whether the index enforces uniqueness.
    /// </summary>
    public bool IsUnique { get; set; }

    /// <summary>
    /// Whether the index is clustered.
    /// </summary>
    public bool IsClustered { get; set; }

    /// <summary>
    /// Whether this is a unique constraint rather than a unique index.
    /// </summary>
    public bool IsUniqueConstraint { get; set; }

    /// <summary>
    /// The key columns in key order. A descending column ends with <c> DESC</c>.
    /// </summary>
    public List<string> KeyColumns { get; set; } = new List<string>();

    /// <summary>
    /// The included (non-key) columns, sorted by name.
    /// </summary>
    public List<string> IncludedColumns { get; set; } = new List<string>();

    /// <summary>
    /// The filter definition of a filtered index, otherwise <c>null</c>.
    /// </summary>
    public string FilterDefinition { get; set; }

    /// <summary>
    /// A one-line description of everything compared, used to detect and
    /// report differences between two databases.
    /// </summary>
    public string Describe()
    {
        var description = $"{( IsClustered ? "CLUSTERED" : "NONCLUSTERED" )}{( IsUnique ? " UNIQUE" : string.Empty )}{( IsUniqueConstraint ? " CONSTRAINT" : string.Empty )} ({string.Join( ", ", KeyColumns )})";

        if ( IncludedColumns.Count > 0 )
        {
            description += $" INCLUDE ({string.Join( ", ", IncludedColumns )})";
        }

        if ( FilterDefinition != null )
        {
            description += $" WHERE {FilterDefinition}";
        }

        return description;
    }
}

/// <summary>
/// A foreign key declared on a table.
/// </summary>
internal sealed class SchemaCatalogForeignKey
{
    /// <summary>
    /// The constraint name.
    /// </summary>
    public string Name { get; set; }

    /// <summary>
    /// The referencing columns, in constraint order.
    /// </summary>
    public List<string> Columns { get; set; } = new List<string>();

    /// <summary>
    /// The <c>schema.table</c> key of the referenced table.
    /// </summary>
    public string ReferencedTable { get; set; }

    /// <summary>
    /// The referenced columns, in constraint order.
    /// </summary>
    public List<string> ReferencedColumns { get; set; } = new List<string>();

    /// <summary>
    /// Whether deleting the referenced row cascades to this table.
    /// </summary>
    public bool IsCascadeDelete { get; set; }

    /// <summary>
    /// The <c>ON DELETE</c> action as SQL Server reports it, such as
    /// <c>NO_ACTION</c>, <c>CASCADE</c> or <c>SET_NULL</c>.
    /// </summary>
    public string DeleteAction { get; set; } = "NO_ACTION";

    /// <summary>
    /// A one-line description of everything compared.
    /// </summary>
    public string Describe()
    {
        return $"({string.Join( ", ", Columns )}) REFERENCES {ReferencedTable} ({string.Join( ", ", ReferencedColumns )}) ON DELETE {DeleteAction}";
    }
}

/// <summary>
/// A view, stored procedure, function or trigger.
/// </summary>
internal sealed class SchemaCatalogModule
{
    /// <summary>
    /// The <c>schema.name</c> key.
    /// </summary>
    public string Key { get; set; }

    /// <summary>
    /// The object type as SQL Server reports it, such as <c>VIEW</c> or <c>SQL_STORED_PROCEDURE</c>.
    /// </summary>
    public string ObjectType { get; set; }

    /// <summary>
    /// The definition with line endings normalized to <c>\n</c> and
    /// trailing whitespace removed from each line.
    /// </summary>
    public string Definition { get; set; }
}
